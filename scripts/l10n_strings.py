PLACEHOLDER = re.compile(r'\{(\w+)\}')


def build(index, locale):
    out = {'@@locale': locale}
    for key, values in S.items():
        text = values[index]
        out[key] = text
        names = PLACEHOLDER.findall(values[0])
        if names and index == 0:
            out[f'@{key}'] = {'placeholders': {name: {'type': 'String'} for name in names}}
    return out


